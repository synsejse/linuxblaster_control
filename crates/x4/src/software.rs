/// Signed bass/treble -100..100; ten fixed frequency anchors, normalized by max gain.
pub fn tone_curve(bass: i8, treble: i8, max_gain: f32) -> Result<[f32; 10]> {
    if !(-100..=100).contains(&bass)
        || !(-100..=100).contains(&treble)
        || !max_gain.is_finite()
        || max_gain < 0.0
    {
        return Err(invalid("Invalid tone controls"));
    }
    let b50 = [
        0.5222222,
        0.4555556,
        0.22222224,
        0.044444446,
        0.,
        0.,
        0.,
        0.,
        0.,
        0.,
    ];
    let b100 = [
        1.1111112,
        1.,
        0.66666675,
        0.31111112,
        0.12222223,
        0.033333335,
        0.,
        0.,
        0.,
        0.,
    ];
    let t50 = [
        0.,
        0.,
        0.,
        0.,
        0.015151515,
        0.06060606,
        0.16666666,
        0.37878788,
        0.530303,
        0.6212121,
    ];
    let t100 = [
        0.,
        0.,
        0.,
        0.015151515,
        0.06060606,
        0.12121212,
        0.28787878,
        0.6363636,
        1.,
        1.2121212,
    ];
    fn part(v: i8, a: f32, b: f32) -> f32 {
        let n = (v as f32).abs() / 50.;
        (if n <= 1. {
            a * n
        } else {
            a + (b - a) * (n - 1.)
        }) * (v as f32).signum()
    }
    Ok(std::array::from_fn(|i| {
        (part(bass, b50[i], b100[i]) + part(treble, t50[i], t100[i])) * max_gain
    }))
}
/// Creative UI adds the new-minus-old tone curve to existing EQ and clamps.
pub fn adjust_tone(
    bands: [f32; 10],
    old: (i8, i8),
    new: (i8, i8),
    max_gain: f32,
) -> Result<[f32; 10]> {
    if bands.iter().any(|x| !x.is_finite()) {
        return Err(invalid("Nonfinite EQ"));
    }
    let a = tone_curve(old.0, old.1, max_gain)?;
    let b = tone_curve(new.0, new.1, max_gain)?;
    Ok(std::array::from_fn(|i| {
        (bands[i] + b[i] - a[i]).clamp(-max_gain, max_gain)
    }))
}
