//! Host software curves reconstructed from Android 2.11.08 static numeric evidence.
//! Tables are UI policy, not firmware quantization or extra DSP effects.
use crate::protocol::{Result, invalid};
#[derive(Debug, Clone, Copy)]
pub enum PercentTable {
    Playback,
    Playback90,
    Recording9,
    Monitoring9,
    Recording6,
    Monitoring6,
    DigitalMonitoring,
}
impl PercentTable {
    pub fn values(self) -> &'static [f32; 101] {
        match self {
            Self::Playback => &F450A,
            Self::Playback90 => &F451B,
            Self::Recording9 => &F452C,
            Self::Monitoring9 => &F453D,
            Self::Recording6 => &F454E,
            Self::Monitoring6 => &F455F,
            Self::DigitalMonitoring => &F456G,
        }
    }
    pub fn encode(self, percent: u8) -> Result<i16> {
        if percent > 100 {
            return Err(invalid("Percentage outside 0..100"));
        }
        Ok((self.values()[percent as usize] * 256.0).floor() as i16)
    }
    pub fn decode(self, raw: i16) -> u8 {
        self.values()
            .iter()
            .rposition(|v| *v <= raw as f32 / 256.0)
            .unwrap_or(0) as u8
    }
}
